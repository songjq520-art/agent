# B 组 13 项，一项都不能少。
EXPECTED_B_ITEMS = {4, 24, 27, 28, 31, 32, 34, 37, 42, 43, 46, 47, 49}


def test_b_group_phrases_cover_all_13_items():
    """B 组 13 项每项都有 5 条新问法/新场景，一项不少。"""
    assert set(B_GROUP_PHRASES) == EXPECTED_B_ITEMS
    assert len(B_GROUP_PHRASES) == 13


def test_each_item_has_five_distinct_phrases():
    """每项 5 条，条条非空、条条不一样——重复的问法验不出泛化。"""
    for item, phrases in B_GROUP_PHRASES.items():
        assert len(phrases) == 5, f"{item} 号不是 5 条"
        assert all(isinstance(p, str) and p.strip() for p in phrases), f"{item} 号有空条"
        assert len(set(phrases)) == 5, f"{item} 号有重复条"
